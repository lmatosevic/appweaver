import path from 'node:path';
import fsp from 'node:fs/promises';
import prettier from 'prettier';
import { KindGuard, TModule, TObject, TSchema, Type } from '@sinclair/typebox';
import { ModelToTypeScript } from '@sinclair/typebox-codegen';
import {
  DateType,
  EnumType,
  isArray,
  NullType,
  ResourceModel
} from '@appweaver/common';
import { ensureDirExists } from '../utils';

/**
 * Generates TypeScript type definitions for the given resource models and writes them to a specified directory.
 *
 * @param {Record<string, ResourceModel>} models - A set of resource models for which TypeScript types will be generated.
 * @param {string} typesPath - The relative path to the directory where the generated types will be written.
 * @param {boolean} [quiet=false] - If true, suppresses detailed logging during the operation.
 * @param {boolean} [registry=true] - Whether to register the types of every model in the resource registry, which
 * lets the factories and injection functions infer them from a model name.
 * @return {Promise<number>} A promise that resolves to a status code: `0` for success, `2` for failure.
 */
export async function generateTypes(
  models: Record<string, ResourceModel>,
  typesPath: string,
  quiet: boolean = false,
  registry: boolean = true
): Promise<number> {
  const cwd = process.cwd();

  try {
    await ensureDirExists(path.join(cwd, typesPath));

    const resourceModels: Record<string, TSchema> = {};
    // The generated type names of every model, in the order they are emitted,
    // so each model group can be written out followed by its own query type
    const modelTypeNames: Record<string, string[]> = {};

    for (const [name, schema] of Object.entries(models)) {
      if (schema.config.generateTypes === false) {
        continue;
      }

      const modelSchemas: [string, TObject][] = [
        [name, schema.readModel],
        [`${name}Single`, schema.readOneModel],
        [`${name}Multiple`, schema.readManyModel],
        [`${name}Create`, schema.createOneModel],
        [`${name}Update`, schema.updateOneModel],
        [`${name}RelationCreate`, schema.relationCreateModel],
        [`${name}RelationUpdate`, schema.relationUpdateModel],
        [`${name}RelationInput`, schema.relationInputModel]
      ];

      for (const [typeName, typeSchema] of modelSchemas) {
        resourceModels[typeName] = transformUnsafeTypes(typeSchema);
      }

      modelTypeNames[name] = modelSchemas.map(([typeName]) => typeName);
    }

    const module = Type.Module(resourceModels);

    const typesContent: string[] = [
      `// Generated by Appweaver. Please do not edit this file manually.`,
      ``
    ];

    const registered = registry && Object.keys(models).length > 0;

    if (Object.keys(modelTypeNames).length > 0 || registered) {
      typesContent.push(
        `import { AggregateSelect, IResourceService, QueryFilter, QuerySort } from '@appweaver/common';`,
        ``
      );
    }

    for (const [name, typeNames] of Object.entries(modelTypeNames)) {
      for (const typeName of typeNames) {
        typesContent.push(generateTypeScriptType(module, typeName), ``);
      }

      typesContent.push(`export type ${name}Query = QueryFilter<${name}>;`, ``);
      // The sort type is built from the query output model, so it only offers
      // the relations included in a query response and their count fields
      typesContent.push(
        `export type ${name}Sort = QuerySort<${name}Multiple>;`,
        ``
      );
      typesContent.push(
        `export type ${name}Aggregate = AggregateSelect<${name}>;`,
        ``
      );
      // Emitted last, with the arguments making the aliases above exactly the
      // inputs its methods accept
      typesContent.push(
        `export type ${name}ResourceService = IResourceService<${name}, ${name}Multiple, ${name}Create, ${name}Update, ${name}Query>;`,
        ``
      );
    }

    if (registered) {
      typesContent.push(registryDeclaration(models, modelTypeNames), ``);
    }

    const outputPath = path.join(cwd, typesPath);

    const prettierConfig = await prettier.resolveConfig(outputPath);
    const formattedTypes = await prettier.format(typesContent.join('\n'), {
      ...prettierConfig,
      filepath: outputPath
    });

    await fsp.writeFile(outputPath, formattedTypes);

    console.log(`Types generated to ${path.relative(cwd, outputPath)}`);

    return 0;
  } catch (error) {
    console.error(
      `Types generation failed.${quiet ? ' Start with --verbose flag to see error details.' : ''}`
    );
    if (!quiet) {
      console.error(error);
    }
    return 2;
  }
}

/**
 * Builds the declaration registering the types of every model in the resource registry of `@appweaver/common`. A
 * model without generated types is registered with loose types, so its name is still accepted.
 */
function registryDeclaration(
  models: Record<string, ResourceModel>,
  modelTypeNames: Record<string, string[]>
): string {
  const entries = Object.entries(models).map(([name, model]) => {
    const relationNames = Object.keys(model.config.relations ?? {});
    const relations =
      relationNames.length > 0
        ? relationNames.map((relation) => `'${relation}'`).join(' | ')
        : 'never';

    if (!modelTypeNames[name]) {
      return `    ${name}: { model: any; single: any; multiple: any; create: any; update: any; query: any; service: IResourceService; relations: string };`;
    }

    return `    ${name}: { model: ${name}; single: ${name}Single; multiple: ${name}Multiple; create: ${name}Create; update: ${name}Update; query: ${name}Query; service: ${name}ResourceService; relations: ${relations} };`;
  });

  return [
    `declare module '@appweaver/common' {`,
    `  interface ResourceRegistry {`,
    ...entries,
    `  }`,
    `}`
  ].join('\n');
}

function generateTypeScriptType(
  module: TModule<{ [p: string]: TSchema }, { [p: string]: TSchema }>,
  name: string
): string {
  const model: TSchema = module.Import(name);
  const schema = model.$defs[name];
  return ModelToTypeScript.GenerateType({ types: [schema] }, name);
}

function transformUnsafeTypes(schema: TObject): TObject {
  const properties: Record<string, TSchema> = {};

  for (const [name, field] of Object.entries(schema.properties)) {
    if (field.type === 'string' && isArray(field.enum)) {
      // A new schema, which has to be marked optional again like the field
      const enumType = EnumType(field.enum);
      properties[name] = KindGuard.IsOptional(field)
        ? Type.Optional(enumType)
        : enumType;
    } else if (
      field.type === 'string' &&
      ['date-time', 'date'].includes(field.format)
    ) {
      properties[name] = DateType(field);
    } else {
      properties[name] = field;
    }

    if (field.nullable === true) {
      properties[name] = NullType(properties[name]);
    }

    // A nullable model reference points at the nullable variant of that model,
    // a schema of its own the response serializer can expand once. The type is
    // written as the union it stands for instead.
    const nullableRef = field.$ref?.match(/^(.+Single)Nullable$/)?.[1];
    if (nullableRef) {
      properties[name] = NullType(Type.Ref(nullableRef));
    }
  }

  return Type.Object(properties, { ...schema });
}
