import path from 'node:path';
import fsp from 'node:fs/promises';
import {
  AuditFields,
  capitalize,
  config,
  DatabaseType,
  FieldDefault,
  FileField,
  FilesConfig,
  IdField,
  idFieldGenerator,
  idFieldType,
  IndexConfig,
  isArray,
  isBoolean,
  isNumber,
  isRelationArray,
  isRelationOwner,
  isResourceAuthModel,
  isString,
  plural,
  RelationConfig,
  RelationField,
  resolveDatabaseType,
  ResourceModel,
  Runtime,
  ScalarConfig,
  ScalarField,
  uncapitalize
} from '@appweaver/common';
import { ensureDirExists, relativePathFrom, runProcess } from '../utils';

const INDEX_SORT_PREFIXES: Record<string, string> = {
  '-': 'Desc',
  '+': 'Asc'
};

const UUID_LENGTH = 36;

const CUID_LENGTHS: Record<string, number> = {
  '': 25,
  '2': 24
};

const NANOID_LENGTH = 21;

const UUID_NATIVE_TYPES: Partial<Record<DatabaseType, string>> = {
  [DatabaseType.PostgresSQL]: '@db.Uuid',
  [DatabaseType.SQLServer]: '@db.UniqueIdentifier',
  [DatabaseType.MySQL]: `@db.Char(${UUID_LENGTH})`
};

type PrismaSchemaField = {
  name: string;
  type: string;
  attributes?: string[];
  /** Marks a generated foreign key column rather than a relation field */
  foreignKey?: boolean;
};

type IdColumn = {
  type: string;
  nativeType?: string;
};

type IdColumnResolver = (modelName: string) => IdColumn;

const defaultIdColumn = (): IdColumn => ({ type: 'Int' });

type PrismaSchemaModel = {
  id: PrismaSchemaField;
  scalars: PrismaSchemaField[];
  relations: PrismaSchemaField[];
  files: PrismaSchemaField[];
  audit: PrismaSchemaField[];
  index: string[];
  tableName?: string;
  extra?: Record<string, PrismaSchemaField[]>;
};

/**
 * Generates a Prisma schema file based on the provided resource models and saves it to the specified file path.
 *
 * @param {Record<string, ResourceModel>} models - An object containing resource model configurations, where each key is
 * the model name.
 * @param {string} schemaPath - The file path where the generated Prisma schema should be stored.
 * @param {string} clientPath - The file path where the Prisma client output should be generated.
 * @param {boolean} [quiet=false] - Optional flag to suppress logs. Default is false.
 * @return {Promise<number>} A promise that resolves to the number of models processed for the schema generation.
 */
export async function generateSchema(
  models: Record<string, ResourceModel>,
  schemaPath: string,
  clientPath: string,
  quiet: boolean = false
): Promise<number> {
  const cwd = process.cwd();

  try {
    const relationErrors = validateRelations(models);
    if (relationErrors.length > 0) {
      for (const relationError of relationErrors) {
        console.error(relationError);
      }
      console.error(
        'Schema generation failed due to inconsistent relation definitions.'
      );
      return 2;
    }

    await ensureDirExists(path.join(cwd, schemaPath));

    const prismaModels: Record<string, PrismaSchemaModel> = {};
    const prismaEnums: Record<string, string[]> = {};

    const dbType = databaseType();
    const relativeOutputPath = relativePathFrom(schemaPath, clientPath);

    const schemaContent = [
      `// This is your Prisma schema file,`,
      `// learn more about it in the docs: https://pris.ly/d/prisma-schema`,
      ``,
      `// Generated by Appweaver. Please do not edit this file manually.`,
      ``,
      `datasource db {`,
      `  provider = "${dbType}"`,
      `}`,
      ``,
      `generator client {`,
      `  provider = "prisma-client"`,
      `  output   = "${relativeOutputPath}"`,
      config.APP_RUNTIME === Runtime.Bun ? '  runtime  = "bun"' : undefined,
      `}`,
      ``
    ].filter((l) => l !== undefined);

    let authModel: ResourceModel | undefined;
    for (const model of Object.values(models)) {
      if (isResourceAuthModel(model)) {
        authModel = model;
        break;
      }
    }

    // A foreign key column has to match the primary key column it references,
    // native type included, or the database rejects the constraint
    const idColumnOf: IdColumnResolver = (modelName) => {
      const id = models[capitalize(modelName)]?.config?.id;
      return { type: prismaIdType(id), nativeType: idNativeType(id) };
    };

    // Create Prisma models and enums from resource model config
    for (const [name, schema] of Object.entries(models)) {
      if (schema.config.generateSchema === false) {
        continue;
      }

      prismaModels[name] = {
        id: createIdSchema(schema.config.id),
        scalars: createScalarsSchema(name, schema.config.scalars),
        relations: createRelationsSchema(
          name,
          schema.config.relations,
          idColumnOf
        ),
        files: createFilesSchema(name, schema.config.files, idColumnOf('File')),
        audit: createAuditSchema(name, authModel, schema.config.audit),
        index: createIndexSchema(schema.config.index),
        tableName: schema.config.tableName
      };

      for (const [fieldName, scalar] of Object.entries(
        schema.config.scalars ?? {}
      )) {
        if (scalar.type === 'enum' && scalar.values?.length) {
          prismaEnums[`${name}${capitalize(fieldName)}`] = scalar.values;
        }
      }
    }

    // Resolve model relations to match Prisma schema relationship convention
    const createdByAuthUser: PrismaSchemaField[] = [];
    const fileFields: PrismaSchemaField[] = [];
    for (const [name, model] of Object.entries(prismaModels)) {
      const modelSchema = Object.entries(models).find(
        ([key]) => key === name
      )?.[1];

      for (const relation of model.relations) {
        if (relation.foreignKey) {
          continue;
        }

        const relationConfig = modelSchema?.config.relations?.[relation.name];
        if (!relationConfig) {
          // Skip auto-generated back reference fields added by other models
          continue;
        }

        const referencedName = relation.type
          .replaceAll('[]', '')
          .replaceAll('?', '');
        const referencedModel = prismaModels[referencedName];

        const mappedField = referencedModel.relations.find(
          (r) => r.name === relationConfig.mappedBy
        );
        if (mappedField?.foreignKey) {
          continue;
        }

        if (mappedField && mappedField.attributes?.length) {
          // Ensure that mapped fields have the same reference name. The name of
          // the relation is replaced while any foreign key configuration on the
          // owning side is preserved.
          const relationAttribute = mappedField.attributes[0];
          const relationParts = relationAttribute.split('"');
          const referenceName = relation.attributes?.[0].split('"')[1];
          relationParts.splice(1, 1, `${referenceName}`);
          mappedField.attributes[0] = relationParts.join('"');
        } else {
          // For unmapped relations add a default back reference field matching
          // the relation type, using the same reference name
          const referenceName = relation.attributes?.[0].split('"')[1];
          const owner = isRelationOwner(relationConfig);

          if (relationConfig.type === 'manyToMany' || owner) {
            // Inverse of a manyToMany relation or of an owning side: for
            // oneToOne a single optional field, otherwise a list field
            const single = relationConfig.type === 'oneToOne';
            const refName = single
              ? uncapitalize(name)
              : uncapitalize(plural(name));
            if (!referencedModel.relations.some((r) => r.name === refName)) {
              referencedModel.relations.push({
                name: refName,
                type: single ? `${name}?` : `${name}[]`,
                attributes: [`@relation("${referenceName}")`]
              });
            }
          } else {
            // A non-owning side declared alone: the referenced model holds the
            // foreign key column
            const refName = uncapitalize(name);
            const refFieldName = `${refName}Id`;
            if (!referencedModel.relations.some((r) => r.name === refName)) {
              const idColumn = idColumnOf(name);
              referencedModel.relations.push({
                name: refName,
                type: `${name}?`,
                attributes: [
                  `@relation("${referenceName}", fields: [${refFieldName}], references: [id])`
                ]
              });
              referencedModel.relations.push({
                name: refFieldName,
                type: `${idColumn.type}?`,
                attributes: [
                  ...(relationConfig.type === 'oneToOne' ? ['@unique'] : []),
                  ...nativeTypeAttributes(idColumn.nativeType)
                ],
                foreignKey: true
              });
            }
          }
        }
      }

      for (const auditField of model.audit) {
        if (auditField.name === 'createdBy') {
          const referenceName = auditField.attributes?.[0].split('"')[1];
          createdByAuthUser.push({
            name: `created${plural(name)}`,
            type: `${name}[]`,
            attributes: [`@relation("${referenceName}")`]
          });
        }
      }

      for (const fileField of model.files) {
        const referenceName = fileField.attributes?.[0].split('"')[1];
        if (referenceName) {
          fileFields.push({
            name: `${fileField.name}${plural(name)}`,
            type: `${name}[]`,
            attributes: [`@relation("${referenceName}")`]
          });
        }
      }
    }

    // Add auth model ownership relations
    const authUserModel = prismaModels[authModel?.name ?? ''];
    if (authUserModel) {
      authUserModel.extra = {
        'Ownership models referenced with createdById column': createdByAuthUser
      };
    }

    // Add file fields relations
    const fileModel = prismaModels['File'];
    if (fileModel) {
      fileModel.extra = {
        'Related models with file columns': fileFields
      };
    }

    // Add Prisma models to the schema content
    for (const [name, model] of Object.entries(prismaModels)) {
      schemaContent.push(`model ${name} {`);

      // Group 1: id + scalars
      const initialFields = [model.id, ...model.scalars];
      const { nameLength, typeLength } = calculateMaxLengths(initialFields);
      schemaContent.push(buildPrismaField(model.id, nameLength, typeLength));
      for (const scalar of model.scalars) {
        schemaContent.push(buildPrismaField(scalar, nameLength, typeLength));
      }

      // Group 2: relations
      if (model.relations.length > 0) {
        schemaContent.push(``);
        schemaContent.push(`  /// Related columns`);
        const { nameLength, typeLength } = calculateMaxLengths(model.relations);
        for (const relation of model.relations) {
          schemaContent.push(
            buildPrismaField(relation, nameLength, typeLength)
          );
        }
      }

      // Group 3: files
      if (model.files.length > 0) {
        schemaContent.push(``);
        schemaContent.push(`  /// File columns`);
        const { nameLength, typeLength } = calculateMaxLengths(model.files);
        for (const file of model.files) {
          schemaContent.push(buildPrismaField(file, nameLength, typeLength));
        }
      }

      // Group 4: extra fields
      for (const [title, extraFields] of Object.entries(model.extra ?? {})) {
        if (extraFields.length === 0) {
          continue;
        }

        schemaContent.push(``);
        schemaContent.push(`  /// ${title}`);
        const { nameLength, typeLength } = calculateMaxLengths(extraFields);
        for (const extraField of extraFields) {
          schemaContent.push(
            buildPrismaField(extraField, nameLength, typeLength)
          );
        }
      }

      // Group 5: audit
      if (model.audit.length > 0) {
        schemaContent.push(``);
        schemaContent.push(`  /// Audit columns`);
        const { nameLength, typeLength } = calculateMaxLengths(model.audit);
        for (const audit of model.audit) {
          schemaContent.push(buildPrismaField(audit, nameLength, typeLength));
        }
      }

      if (model.index.length) {
        schemaContent.push(``);
      }

      for (const index of model.index) {
        schemaContent.push(`  ${index}`);
      }

      if (model.tableName) {
        schemaContent.push(``);
        schemaContent.push(`  @@map("${model.tableName}")`);
      }

      schemaContent.push(`}`, ``);
    }

    // Add Prisma enums to the schema content
    for (const [name, enumValues] of Object.entries(prismaEnums)) {
      schemaContent.push(`enum ${name} {`);

      for (const value of enumValues) {
        schemaContent.push(`  ${value}`);
      }

      schemaContent.push(`}`, ``);
    }

    const outputPath = path.join(cwd, schemaPath);

    let oldSchema: string | undefined;
    try {
      oldSchema = await fsp.readFile(outputPath, 'utf8');
    } catch (error) {
      // Schema currently does not exist
    }

    await fsp.writeFile(outputPath, schemaContent.join('\n'));

    const code = await runProcess('prisma', ['generate'], { quiet });
    if (code !== 0 && oldSchema) {
      await fsp.writeFile(outputPath, oldSchema);
      console.error(
        `Schema generation failed.${quiet ? ' Start with --verbose flag to see error details.' : ''}`
      );
      return 1;
    } else {
      console.log(`Schema generated to ${path.relative(cwd, schemaPath)}`);
      return 0;
    }
  } catch (error) {
    console.error('Schema generation failed', error);
    return 2;
  }
}

function buildPrismaField(
  field: PrismaSchemaField,
  nameLength = 0,
  typeLength = 0
): string {
  const paddedName = field.name.padEnd(nameLength);
  const paddedType = field.type.padEnd(typeLength);
  return `  ${paddedName} ${paddedType} ${field.attributes?.join(' ') ?? ''}`.trimEnd();
}

function calculateMaxLengths(fields: PrismaSchemaField[]): {
  nameLength: number;
  typeLength: number;
} {
  let nameLength = 0;
  let typeLength = 0;

  for (const field of fields) {
    if (field.name.length > nameLength) {
      nameLength = field.name.length;
    }
    if (field.type.length > typeLength) {
      typeLength = field.type.length;
    }
  }

  return { nameLength, typeLength };
}

function prismaIdType(id?: IdField): string {
  switch (idFieldType(id)) {
    case 'string':
      return 'String';
    case 'bigInt':
      return 'BigInt';
    default:
      return 'Int';
  }
}

function parseGenerator(
  generator?: string
): { name: string; arg: string } | undefined {
  const match = generator?.match(/^(\w+)\(([^)]*)\)$/);
  return match ? { name: match[1], arg: match[2].trim() } : undefined;
}

function generatorNativeType(
  generator?: string,
  dbType: DatabaseType = databaseType()
): string | undefined {
  if (dbType === DatabaseType.Sqlite) {
    return undefined;
  }

  const parsed = parseGenerator(generator);
  if (!parsed) {
    return undefined;
  }

  // The argument of `uuid()` and `cuid()` selects the version, the one of
  // `nanoid()` the length of the generated value
  switch (parsed.name) {
    case 'uuid':
      return UUID_NATIVE_TYPES[dbType] ?? `@db.VarChar(${UUID_LENGTH})`;
    case 'cuid':
      return varCharType(CUID_LENGTHS[parsed.arg]);
    case 'nanoid':
      return varCharType(
        parsed.arg ? Number(parsed.arg) : NANOID_LENGTH,
        NANOID_LENGTH
      );
    default:
      return undefined;
  }
}

function varCharType(length?: number, fallback?: number): string | undefined {
  const size = Number.isFinite(length) ? length : fallback;
  return size ? `@db.VarChar(${size})` : undefined;
}

function idNativeType(id?: IdField): string | undefined {
  return idFieldType(id) === 'string'
    ? generatorNativeType(idFieldGenerator(id))
    : undefined;
}

function createIdSchema(id?: IdField): PrismaSchemaField {
  return {
    name: 'id',
    type: prismaIdType(id),
    attributes: [
      '@id',
      `@default(${idFieldGenerator(id)})`,
      ...nativeTypeAttributes(idNativeType(id))
    ]
  };
}

function nativeTypeAttributes(nativeType?: string): string[] {
  return nativeType ? [nativeType] : [];
}

function createScalarsSchema(
  modelName: string,
  scalars: ScalarConfig = {}
): PrismaSchemaField[] {
  const fields: PrismaSchemaField[] = [];

  for (const [name, scalar] of Object.entries(scalars)) {
    fields.push(createScalarSchema(name, modelName, scalar));
  }

  return fields;
}

function createScalarSchema(
  name: string,
  modelName: string,
  scalar: ScalarField
): PrismaSchemaField {
  const attributes: string[] = [];

  const isSqlite = databaseType() === DatabaseType.Sqlite;

  const sanitize = (val: FieldDefault) => {
    if (isNumber(val) || isBoolean(val)) {
      return val;
    } else if (isString(val)) {
      return val.replace(/"/g, '\\"');
    } else {
      return JSON.stringify(val).replace(/"/g, '\\"');
    }
  };

  let typeSuffix = scalar.required === false ? '?' : '';
  if (scalar.array) {
    typeSuffix = '[]';
  }

  const type =
    scalar.type === 'enum' && scalar.values?.length
      ? `${modelName}${capitalize(name)}${typeSuffix}`
      : `${capitalize(scalar.type)}${typeSuffix}`;

  if (scalar.unique) {
    attributes.push(`@unique`);
  }

  let defaultAttribute: string | undefined;

  if (scalar.default !== undefined) {
    if (['string', 'dateTime', 'json'].includes(scalar.type) && !scalar.array) {
      defaultAttribute = `@default("${sanitize(scalar.default)}")`;
    } else if (scalar.array) {
      const defaultValues = isArray(scalar.default)
        ? scalar.default
        : [scalar.default];
      const mappedValues = defaultValues
        .map((v: any) =>
          ['string', 'dateTime', 'json'].includes(scalar.type)
            ? `"${sanitize(v)}"`
            : `${v}`
        )
        .join(', ');
      defaultAttribute = `@default([${mappedValues}])`;
    } else {
      defaultAttribute = `@default(${sanitize(scalar.default)})`;
    }
  } else if (scalar.defaultGenerator !== undefined) {
    defaultAttribute = `@default(${scalar.defaultGenerator})`;
  } else if (scalar.defaultExpression?.length) {
    defaultAttribute = `@default(dbgenerated("${scalar.defaultExpression}"))`;
  }

  if (defaultAttribute) {
    attributes.push(defaultAttribute);
  }

  if (scalar.type === 'string' && !isSqlite) {
    // The generator width wins over `maxLength`, which only bounds the API input
    const nativeType =
      generatorNativeType(scalar.defaultGenerator) ??
      varCharType(scalar.maxLength);
    if (nativeType) {
      attributes.push(nativeType);
    }
  }

  return {
    name,
    type,
    attributes
  };
}

/**
 * Validates the consistency of every bidirectional relation pair linked through
 * `mappedBy`. Both sides must declare the same relation type, reference each
 * other's model, and for `oneToOne` and `oneToMany` relations exactly one side
 * must be the owner. Single-sided relations (where the mapped field does not
 * exist) are left to the back reference generation and are not validated.
 *
 * @param {Record<string, ResourceModel>} models - All resource models keyed by name.
 * @return {string[]} A list of human-readable error messages, empty when all
 * relation pairs are consistent.
 */
function validateRelations(models: Record<string, ResourceModel>): string[] {
  const errors: string[] = [];
  const visited = new Set<string>();

  for (const [name, model] of Object.entries(models)) {
    const relations = model.config?.relations ?? {};

    for (const [fieldName, relation] of Object.entries(relations)) {
      if (!relation.mappedBy) {
        continue;
      }

      const mapped =
        models[relation.model]?.config?.relations?.[relation.mappedBy];
      if (!mapped) {
        continue;
      }

      const relationLabel = `${name}.${fieldName}`;
      const mappedLabel = `${relation.model}.${relation.mappedBy}`;

      // Each pair is reachable from both of its sides, so report it only once
      const pairKey = [relationLabel, mappedLabel].sort().join('|');
      if (visited.has(pairKey)) {
        continue;
      }
      visited.add(pairKey);

      if (mapped.model !== name) {
        errors.push(
          `Relation '${relationLabel}' is mapped by '${mappedLabel}', which references model '${mapped.model}' instead of '${name}'.`
        );
        continue;
      }

      if (mapped.type !== relation.type) {
        errors.push(
          `Relation type mismatch: '${relationLabel}' is declared as '${relation.type}' but '${mappedLabel}' is declared as '${mapped.type}'.`
        );
        continue;
      }

      if (relation.type !== 'manyToMany') {
        const ownerCount = [relation, mapped].filter(isRelationOwner).length;
        if (ownerCount === 0) {
          errors.push(
            `Relation owner missing: neither '${relationLabel}' nor '${mappedLabel}' declares 'owner: true' for the '${relation.type}' relation.`
          );
        } else if (ownerCount === 2) {
          errors.push(
            `Relation owner conflict: both '${relationLabel}' and '${mappedLabel}' declare 'owner: true' for the '${relation.type}' relation.`
          );
        }
      }
    }
  }

  return errors;
}

function createRelationsSchema(
  modelName: string,
  relations: RelationConfig = {},
  idColumnOf: IdColumnResolver = defaultIdColumn
): PrismaSchemaField[] {
  const fields: PrismaSchemaField[] = [];

  for (const [name, relation] of Object.entries(relations)) {
    fields.push(
      ...createRelationSchema(
        name,
        modelName,
        relation,
        idColumnOf(relation.model)
      )
    );
  }

  return fields;
}

function createRelationSchema(
  name: string,
  modelName: string,
  relation: RelationField,
  relationIdColumn: IdColumn = defaultIdColumn()
): PrismaSchemaField[] {
  const attributes: string[] = [];
  const relationName = `${modelName}${capitalize(name)}${relation.model}`;
  const relationFieldName = `${name}Id`;
  const relationSuffix = relation.required === false ? '?' : '';
  const array = isRelationArray(relation);
  const owner = isRelationOwner(relation);

  let type: string;
  if (array) {
    type = `${relation.model}[]`;
  } else if (owner) {
    type = `${relation.model}${relationSuffix}`;
  } else {
    // The inverse side of a oneToOne relation must be optional in Prisma
    type = `${relation.model}?`;
  }

  if (owner) {
    const referentialActions: string[] = [];
    if (relation.onDelete) {
      referentialActions.push(`onDelete: ${capitalize(relation.onDelete)}`);
    }
    if (relation.onUpdate) {
      referentialActions.push(`onUpdate: ${capitalize(relation.onUpdate)}`);
    }
    const referentialConfig =
      referentialActions.length > 0 ? `, ${referentialActions.join(', ')}` : '';
    attributes.push(
      `@relation("${relationName}", fields: [${relationFieldName}], references: [id]${referentialConfig})`
    );
  } else {
    attributes.push(`@relation("${relationName}")`);
  }

  const relationFields: PrismaSchemaField[] = [
    {
      name,
      type,
      attributes
    }
  ];

  if (owner) {
    relationFields.push({
      name: relationFieldName,
      type: `${relationIdColumn.type}${relationSuffix}`,
      attributes: [
        ...(relation.type === 'oneToOne' ? ['@unique'] : []),
        ...nativeTypeAttributes(relationIdColumn.nativeType)
      ],
      foreignKey: true
    });
  }

  return relationFields;
}

function createFilesSchema(
  modelName: string,
  files: FilesConfig = {},
  fileIdColumn: IdColumn = defaultIdColumn()
): PrismaSchemaField[] {
  const fields: PrismaSchemaField[] = [];

  for (const [name, file] of Object.entries(files)) {
    fields.push(...createFileSchema(name, modelName, file, fileIdColumn));
  }

  return fields;
}

function createFileSchema(
  name: string,
  modelName: string,
  file: FileField,
  fileIdColumn: IdColumn = defaultIdColumn()
): PrismaSchemaField[] {
  const attributes: string[] = [];
  const type = file.array ? 'File[]' : 'File?';
  const fileRelationName = `${modelName}${capitalize(name)}File`;
  const fileRelationFieldName = `${name}Id`;

  if (file.array) {
    attributes.push(`@relation("${fileRelationName}")`);
  } else {
    attributes.push(
      `@relation("${fileRelationName}", fields: [${fileRelationFieldName}], references: [id])`
    );
  }

  const fileFields: PrismaSchemaField[] = [
    {
      name,
      type,
      attributes
    }
  ];

  if (!file.array) {
    fileFields.push({
      name: fileRelationFieldName,
      type: `${fileIdColumn.type}?`,
      attributes: ['@unique', ...nativeTypeAttributes(fileIdColumn.nativeType)],
      foreignKey: true
    });
  }

  return fileFields;
}

function createAuditSchema(
  modelName: string,
  authModel?: ResourceModel,
  audit: AuditFields = {}
): PrismaSchemaField[] {
  const defaultAudit: AuditFields = {
    updatedAt: true,
    createdAt: true,
    createdById: true
  };
  const mergedAudit = { ...defaultAudit, ...audit };

  const fields: PrismaSchemaField[] = [];

  const authModelName = authModel?.name;

  if (mergedAudit.updatedAt) {
    fields.push({
      name: 'updatedAt',
      type: 'DateTime',
      attributes: ['@updatedAt']
    });
  }

  if (mergedAudit.createdAt) {
    fields.push({
      name: 'createdAt',
      type: 'DateTime',
      attributes: ['@default(now())']
    });
  }

  if (mergedAudit.createdById && authModelName) {
    fields.push({
      name: 'createdBy',
      type: `${authModelName}?`,
      attributes: [
        `@relation("${modelName}CreatedBy${authModelName}", fields: [createdById], references: [id])`
      ]
    });
    fields.push({
      name: 'createdById',
      type: `${prismaIdType(authModel?.config.id)}?`,
      attributes: nativeTypeAttributes(idNativeType(authModel?.config.id)),
      foreignKey: true
    });
  }

  return fields;
}

function createIndexSchema(index?: IndexConfig): string[] {
  const indexes: string[] = [];

  if (!index || index.length === 0) {
    return indexes;
  }

  for (const idx of index) {
    const indexValue = isArray(idx)
      ? `[${idx.map(indexFieldSchema).join(', ')}]`
      : indexFieldSchema(idx);
    const indexExpression = `@@index(${indexValue})`;
    if (!indexes.includes(indexExpression)) {
      indexes.push(indexExpression);
    }
  }

  return indexes;
}

function indexFieldSchema(field: string): string {
  const sort = INDEX_SORT_PREFIXES[field.charAt(0)];
  if (!sort || field.length < 2) {
    return field;
  }
  return `${field.slice(1)}(sort: ${sort})`;
}

function databaseType(): DatabaseType {
  return resolveDatabaseType(config.DATABASE_TYPE, config.DATABASE_URL);
}
